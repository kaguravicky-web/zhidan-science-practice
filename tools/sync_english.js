// Copies the English word lists from the spelling site into mrt/english.js for the phone page.
// Usage (from this repo's root): node tools/sync_english.js [path/to/english-spelling-practice/src/data.ts]
// Run it again whenever a list is added to the spelling site, then bump the version in mrt/index.html.
const fs = require("fs"), path = require("path"), vm = require("vm");
const root = path.join(__dirname, "..");
const src = process.argv[2] || path.join(root, "..", "english-spelling-practice", "src", "data.ts");
const s = fs.readFileSync(src, "utf8");
const decl = s.indexOf("export const defaultSpellingLists");
if (decl < 0) throw new Error("defaultSpellingLists not found in " + src);
const a = s.indexOf("= [", decl) + 2, b = s.indexOf("\n];\n", a) + 2;
const lists = vm.runInNewContext("(" + s.slice(a, b) + ")");
const out = lists.filter(l => l.language !== "zh").map(l => ({
  id: l.id, week: l.week, date: l.date || "",
  items: l.items.map(i => ({id: i.id, word: i.word, text: i.text, definition: i.definition || "",
    synonyms: i.synonyms || [], antonyms: i.antonyms || []}))
}));
let warn = 0;
for (const l of out) for (const i of l.items) {
  const re = new RegExp("\\b" + i.word.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\\b", "i");
  if (!re.test(i.text)) { warn++; console.log(`! ${l.week}: "${i.word}" is not in its sentence (no fill-in question for it)`); }
}
const file = path.join(root, "mrt", "english.js");
fs.writeFileSync(file, "// Generated by tools/sync_english.js from the spelling site. Do not edit by hand.\n" +
  "window.EN_LISTS = " + JSON.stringify(out, null, 1) + ";\n");
console.log(`✓ ${out.length} English lists, ${out.reduce((n, l) => n + l.items.length, 0)} words -> mrt/english.js` + (warn ? ` (${warn} warnings)` : ""));
